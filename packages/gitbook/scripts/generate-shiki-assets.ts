import { $ } from 'bun';
import { createHash } from 'node:crypto';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundledLanguagesInfo } from 'shiki/langs';
import { bundledThemesInfo } from 'shiki/themes';

/**
 * Write every Shiki language and theme as static JSON, so the app loads them on demand
 * instead of bundling them, and generate the catalog of their names.
 */

const scriptDir = dirname(fileURLToPath(import.meta.url));
const staticDir = join(scriptDir, '../public/~gitbook/static');
const codeBlockDir = join(scriptDir, '../src/components/DocumentView/CodeBlock');
const require = createRequire(import.meta.url);
const { version } = require('shiki/package.json') as { version: string };

const languages: Record<string, string> = {};
const languageGrammars: Record<string, string[]> = {};
const grammars = new Map<string, string>();
for (const info of bundledLanguagesInfo) {
    // A language module exports its embedded grammars followed by its own, in registration order.
    const registrations = (await info.import()).default;
    for (const registration of registrations) {
        const json = JSON.stringify(registration);
        const existing = grammars.get(registration.name);
        if (existing !== undefined && existing !== json) {
            throw new Error(`Grammar "${registration.name}" differs between languages`);
        }
        grammars.set(registration.name, json);
    }
    languageGrammars[info.id] = registrations.map((registration) => registration.name);
    languages[info.id] = info.id;
    for (const alias of info.aliases ?? []) {
        languages[alias] ??= info.id;
    }
}

const themes: Record<string, { type: 'light' | 'dark' }> = {};
const themeFiles = new Map<string, string>();
for (const info of bundledThemesInfo) {
    themeFiles.set(info.id, JSON.stringify((await info.import()).default));
    themes[info.id] = { type: info.type };
}

// Hash the content into the path: assets are served immutable, so any change needs a new URL.
const hash = createHash('sha256');
for (const [name, json] of [...grammars, ...themeFiles].sort(compareEntries)) {
    hash.update(name).update('\0').update(json).update('\0');
}
const assetsPath = `shiki/${version}-${hash.digest('hex').slice(0, 8)}`;

await rm(join(staticDir, 'shiki'), { force: true, recursive: true });
await mkdir(join(staticDir, assetsPath, 'grammars'), { recursive: true });
await mkdir(join(staticDir, assetsPath, 'themes'), { recursive: true });

// One file per grammar so embedded grammars are stored and downloaded once.
for (const [name, json] of grammars) {
    await writeFile(join(staticDir, assetsPath, 'grammars', `${name}.json`), json);
}
for (const [id, json] of themeFiles) {
    await writeFile(join(staticDir, assetsPath, 'themes', `${id}.json`), json);
}

await writeFile(
    join(codeBlockDir, 'shiki-catalog.ts'),
    `// Generated by scripts/generate-shiki-assets.ts, do not edit.

export const SHIKI_ASSETS_PATH = ${JSON.stringify(assetsPath)};

/** Every Shiki language id and alias, mapped to the id of its asset. */
export const SHIKI_LANGUAGES: Record<string, string> = ${JSON.stringify(sorted(languages), null, 4)};

/** Grammars to register for each language, embedded ones first. */
export const SHIKI_LANGUAGE_GRAMMARS: Record<string, string[]> = ${JSON.stringify(sorted(languageGrammars), null, 4)};

export function getShikiGrammarAssetPath(name: string): string {
    return \`\${SHIKI_ASSETS_PATH}/grammars/\${name}.json\`;
}

export function getShikiThemeAssetPath(id: string): string {
    return \`\${SHIKI_ASSETS_PATH}/themes/\${id}.json\`;
}
`
);

// Separate from the catalog: plain highlighting only needs theme types and ships in the eager chunk.
await writeFile(
    join(codeBlockDir, 'shiki-themes.ts'),
    `// Generated by scripts/generate-shiki-assets.ts, do not edit.

/** Every bundled Shiki theme id, with its type. */
export const SHIKI_THEMES: Record<string, { type: 'light' | 'dark' }> = ${JSON.stringify(sorted(themes), null, 4)};
`
);

// Format like the rest of the repo so regenerating doesn't leave the committed files modified.
await $`bunx oxfmt ${join(codeBlockDir, 'shiki-catalog.ts')} ${join(codeBlockDir, 'shiki-themes.ts')}`.quiet();

function compareEntries([a]: [string, unknown], [b]: [string, unknown]) {
    // Code-point order keeps the output identical whatever the machine's locale.
    return a < b ? -1 : a > b ? 1 : 0;
}

function sorted<T>(record: Record<string, T>) {
    return Object.fromEntries(Object.entries(record).sort(compareEntries));
}
